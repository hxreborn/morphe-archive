package app.keropatches.tools

import app.keropatches.registry.Catalogue
import app.morphe.patcher.patch.AppTarget
import app.morphe.patcher.patch.Compatibility
import java.io.File
import kotlin.system.exitProcess

/**
 * Writes `patches-list.json`, the file third-party patch indexes read.
 *
 * The manager only needs `patches-bundle.json`, but the community index at
 * `morphe-patches.software` builds its application and patch tables from this
 * file. Generating it from [Catalogue] keeps one description of the bundle: the
 * same objects the tests and the documentation read.
 *
 * This is a development tool, not part of the shipped bundle. It is written by
 * hand against the published schema; no template code was copied.
 *
 * Usage:
 * ```
 * gradlew generatePatchesList
 * ```
 */
fun main(args: Array<String>) {
    if (args.size != 2) {
        System.err.println("Usage: generatePatchesList <version> <output path>")
        exitProcess(2)
    }

    val version = args[0]
    val output = File(args[1]).absoluteFile

    val json = buildString {
        appendLine("{")
        append("  \"NOTE\": ")
        quote(
            "Do NOT manually edit this file. It is regenerated by " +
                "`gradlew generatePatchesList` from the catalogue, and the release " +
                "workflow refreshes it on every release.",
        )
        appendLine(",")
        append("  \"version\": ")
        quote(version)
        appendLine(",")
        appendLine("  \"patches\": [")

        Catalogue.entries.forEachIndexed { index, entry ->
            val patch = entry.patch
            appendLine("    {")
            append("      \"name\": ")
            quote(patch.name)
            appendLine(",")
            append("      \"description\": ")
            quote(patch.description)
            appendLine(",")
            append("      \"default\": ")
            append(patch.default)
            appendLine(",")
            append("      \"category\": ")
            quote(patch.category)
            appendLine(",")
            appendLine("      \"compatiblePackages\": [")

            val packages = patch.compatibility.orEmpty()
            packages.forEachIndexed { packageIndex, compatibility ->
                appendCompatibility(this, compatibility, indent = "        ")
                if (packageIndex != packages.lastIndex) appendLine(",") else appendLine()
            }

            append("      ]")
            appendLine()
            append("    }")
            if (index != Catalogue.entries.lastIndex) appendLine(",") else appendLine()
        }

        appendLine("  ]")
        appendLine("}")
    }

    output.parentFile?.mkdirs()
    output.writeText(json)

    println("Wrote ${output.path}")
    println("  version  : $version")
    println("  patches  : ${Catalogue.entries.size}")
    println("  packages : ${Catalogue.entries.sumOf { it.patch.compatibility.orEmpty().size }}")
}

private fun appendCompatibility(out: StringBuilder, compatibility: Compatibility, indent: String) {
    val inner = "$indent  "
    out.appendLine("$indent{")
    out.append("$inner\"packageName\": ")
    quote(compatibility.packageName, out)
    out.appendLine(",")
    out.append("$inner\"name\": ")
    quote(compatibility.name, out)
    out.appendLine(",")
    out.append("$inner\"description\": ")
    quote(compatibility.description, out)
    out.appendLine(",")
    out.append("$inner\"apkFileType\": ")
    quote(compatibility.apkFileType?.name, out)
    out.appendLine(",")
    out.append("$inner\"appIconColor\": ")
    quote(compatibility.appIconColor?.let { "#%08X".format(it) }, out)
    out.appendLine(",")
    out.append("$inner\"signatures\": ")
    appendStringArray(out, compatibility.signatures.orEmpty().sorted())
    out.appendLine(",")
    out.append("$inner\"formFactor\": ")
    quote(compatibility.formFactor?.name, out)
    out.appendLine(",")
    out.append("$inner\"targets\": [")
    out.appendLine()

    val targets = compatibility.targets
    targets.forEachIndexed { index, target ->
        appendTarget(out, target, "$inner  ")
        if (index != targets.lastIndex) out.appendLine(",") else out.appendLine()
    }

    out.appendLine("$inner]")
    out.append("$indent}")
}

private fun appendTarget(out: StringBuilder, target: AppTarget, indent: String) {
    val inner = "$indent  "
    out.appendLine("$indent{")
    out.append("$inner\"version\": ")
    quote(target.version, out)
    out.appendLine(",")
    out.append("$inner\"versionCodes\": ")
    // The framework expands a single version code to every ABI. Official lists
    // leave the field null in that case, and the index matches on the version
    // name, so an object is emitted only when the codes actually differ.
    val codes = target.versionCodes.orEmpty()
    if (codes.values.distinct().size <= 1) {
        out.append("null")
    } else {
        out.append("{")
        codes.entries.sortedBy { it.key.name }.forEachIndexed { index, (abi, code) ->
            out.append("\"${abi.name.lowercase()}\": $code")
            if (index != codes.size - 1) out.append(", ")
        }
        out.append("}")
    }
    out.appendLine(",")
    out.append("$inner\"isExperimental\": ")
    out.append(target.isExperimental)
    out.appendLine(",")
    out.append("$inner\"minSdk\": ")
    out.append(target.minSdk?.toString() ?: "null")
    out.appendLine(",")
    out.append("$inner\"description\": ")
    quote(target.description, out)
    out.appendLine()
    out.append("$indent}")
}

private fun appendStringArray(out: StringBuilder, values: List<String>) {
    if (values.isEmpty()) {
        out.append("[]")
        return
    }
    out.append("[")
    values.forEachIndexed { index, value ->
        quote(value, out)
        if (index != values.lastIndex) out.append(", ")
    }
    out.append("]")
}

/** Appends [value] as a JSON string, or the literal `null` when it is absent. */
private fun quote(value: String?, out: StringBuilder) {
    if (value == null) {
        out.append("null")
        return
    }
    out.append('"')
    for (character in value) {
        when (character) {
            '"' -> out.append("\\\"")
            '\\' -> out.append("\\\\")
            '\n' -> out.append("\\n")
            '\r' -> out.append("\\r")
            '\t' -> out.append("\\t")
            '\b' -> out.append("\\b")
            '\u000C' -> out.append("\\f")
            else ->
                if (character.code < 0x20) {
                    out.append("\\u%04x".format(character.code))
                } else {
                    out.append(character)
                }
        }
    }
    out.append('"')
}

private fun StringBuilder.quote(value: String?) = quote(value, this)
